import test from '../../test/helpers/bounded-test.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { entryPolicy } from '../policy.mjs';
import { fixture } from '../../dispatch/test/dispatch-fixture.mjs';

const root = path.resolve(fileURLToPath(new URL('../../', import.meta.url)));

test('entry policies keep ordinary landing with workers and supervisor authority at exceptions', t => {
  const f = fixture(t), priorFleet = process.env.HERDR_MONITOR_FLEET;
  process.env.HERDR_MONITOR_FLEET = f.env.HERDR_MONITOR_FLEET;
  t.after(() => {
    if (priorFleet === undefined) delete process.env.HERDR_MONITOR_FLEET;
    else process.env.HERDR_MONITOR_FLEET = priorFleet;
  });
  const context = { canonical: f.repo, org: f.org };
  const worker = entryPolicy({ ...context, role: 'worker' }, root);
  assert.ok(worker.includes(`${root}/lanes/lane.mjs`));
  assert.match(worker, /promote TOPIC --expected-head-from-worktree/);
  assert.doesNotMatch(worker, /--expected-head FULL_/);
  assert.match(worker, /record the resulting committed candidate head, and verify the command's captured head matches it/);
  assert.match(worker, /Hand immutable landed base\/head and producer evidence through your report to the single existing record queue-review path/);
  assert.match(worker, /the line service creates\/dispatches ONE independent async post-code diff\/evidence review, cap1/);
  assert.match(worker, /Never start a manual settle\/lane review, add a second reviewer, wait for a verdict to land, or replace an existing\/UNKNOWN attempt/);
  assert.doesNotMatch(worker, /review TOPIC|--parallel-review|--captured-head|--captured-base/);
  assert.match(worker, /zero reviewer suites/);
  assert.match(worker, /A final report and review verdict are not pre-main gates/);
  assert.match(worker, /Own at most one formal correction, then fix forward/);
  assert.match(worker, /retain an existing bootstrap watcher and its saved recipient\/runtime\/claims/);
  assert.match(worker, /exceptions to your PROJECT SUPERVISOR at its recorded project-specific exception address/);
  assert.match(worker, /native identity\/claim.*source\/CAS\/fast-forward, STOP, HOLD and archives/);
  assert.match(worker, /Workers never run the release gate or start housekeeping/);
  assert.match(worker, /signed landing\/report clocks/);
  assert.doesNotMatch(worker, /--role supervisor|supervisor\/supervisor.mjs|--start/);
  const chat = entryPolicy({ ...context, role: 'chat' }, root);
  assert.match(chat, /follow-up belongs to the recorded owning worker/);
  assert.doesNotMatch(chat, /Route routine notices to.*supervisor/);
  const supervisor = entryPolicy({ ...context, role: 'supervisor' }, root).replace(/\s+/g, ' ');
  assert.match(supervisor, /reserve supervisor mutations for actual exceptions\/recovery/);
  assert.match(supervisor, /Workers never borrow this role/);
  assert.match(supervisor, /Existing saved jobs and watchers keep their original recipients/);
  assert.match(supervisor, /bootstrap watcher already targeting the supervisor stays intact/);
  assert.match(supervisor, /forwards ordinary follow-up to the recorded owner without another watcher or review/);
  assert.match(supervisor, /New cold dispatches without --to send routine notices to their own worker/);
  assert.match(supervisor, /Unsafe, native, ownership, reserved and failed exceptions go to the PROJECT SUPERVISOR/);
  assert.match(supervisor, /forward ordinary follow-up to their recorded owner without duplicate intake\/review/);
  assert.match(supervisor, /ONE async post-code immutable diff\/evidence review per source item\/landed head, cap1/);
  assert.match(supervisor, /name verifier\/evidence in the normal receipt/);
  assert.match(supervisor, /New cold source calls use pinned Node20\.19\.4 and matching HERDR_BRAIN_ROOT/);
  assert.match(supervisor, /saved retries and native ownership remain intact/);
  assert.match(supervisor, /Instructions do not activate a runtime/);
  assert.doesNotMatch(supervisor, /Route routine notices to.*supervisor/);
  const dispatch = fs.readFileSync(path.join(root, 'dispatch/README.md'), 'utf8');
  assert.match(dispatch, /after `record worker` and fresh live occupant verification/);
  assert.match(dispatch, /retries retain it/);
  assert.match(dispatch, /HERDR_BRAIN_ROOT=\/CANONICAL \/PINNED\/NODE \/CANONICAL\/dispatch\/dispatch\.mjs/);
  assert.match(dispatch, /Retries and `--from-run` continuations always retain their saved claim\/runtime/);
  assert.match(dispatch, /must not launch a duplicate review/);
  assert.match(dispatch, /selector never adopts old work or changes a project\/global pin/);
  assert.match(dispatch, /installed `current`, running sessions and saved claimed operations/);
});
