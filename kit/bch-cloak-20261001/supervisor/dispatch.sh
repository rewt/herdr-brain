#!/bin/zsh
# usage: dispatch.sh ITEM LANE ROUTE HARNESS MODEL EFFORT BRIEF REPORT [BASE]
set -eu
ITEM=$1 LANE=$2 ROUTE=$3 HARN=$4 MODEL=$5 EFF=$6 BRIEF=$7 REPORT=$8 BASE=${9:-}
ROOT=/Users/rewt/development/bastian; REPO=$ROOT/bch-cloak; cd $REPO
[ -s "$BRIEF" ] || { echo "brief missing or empty: $BRIEF (no org run started)"; exit 1; }
herdr agent get supervisor-opus >/dev/null 2>&1 || { echo "notify target supervisor-opus not found: run herdr agent rename <supervisor pane> supervisor-opus (no org run started)"; exit 1; }
WT=/Users/rewt/.herdr/worktrees/bch-cloak/lane-$LANE
RUN=$(org start $ITEM --harness $HARN --model $MODEL --effort $EFF --workspace $WT --report $REPORT --meta route=$ROUTE --meta lane=$LANE | sed -n 's/^\(R-[0-9]*\) started.*/\1/p')
[ -n "$RUN" ] || { echo "org start failed"; exit 1; }
sed -i '' "s/R-RUN/$RUN/g" $BRIEF
cp $ROOT/.org/runs/$RUN/brief.md /tmp/orgctx-$RUN.md
{ cat $BRIEF; printf '\n---\n\n# Org context (generated by org start)\n\n'; cat /tmp/orgctx-$RUN.md; } > $ROOT/.org/runs/$RUN/brief.md
if [ ! -d $WT ]; then node scripts/lane/lane.mjs open $LANE $BASE >/dev/null; node scripts/lane/lane.mjs prepare $LANE > /tmp/prep-$LANE.log 2>&1; fi
if [ -n "$BASE" ]; then git -C $WT merge --ff-only -q $BASE || { echo "reused worktree cannot fast-forward to $BASE"; exit 1; }; echo "worktree HEAD $(git -C $WT rev-parse --short HEAD)"; fi
OUT=$(node scripts/lane/lane.mjs dispatch $LANE --route $ROUTE @$ROOT/.org/runs/$RUN/brief.md 2>&1)
LINE=$(print -r -- "$OUT" | grep "^dispatched '")
AG=$(print -r -- "$LINE" | sed -n "s/^dispatched '\([^']*\)'.*/\1/p")
PANE=$(print -r -- "$LINE" | sed -n 's/.*(pane \([^)]*\)).*/\1/p')
[ -n "$AG" ] && [ -n "$PANE" ] || { echo "dispatch parse failed: $OUT"; exit 1; }
org set $RUN agent=$AG pane=$PANE >/dev/null
# watchers run detached with a log, never in a tab (operator 2026-09-28: tabs piled up in wFN)
mkdir -p .lane/supervisor/watch-logs
env -u HERDR_PANE_ID nohup .lane/supervisor/notify-watch.sh $RUN --to supervisor-opus > .lane/supervisor/watch-logs/$RUN.log 2>&1 < /dev/null &!
echo "$RUN $ITEM agent=$AG pane=$PANE watcher=detached(watch-logs/$RUN.log)"
